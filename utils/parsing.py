"""Разбор данных, которые сайт отдаёт в человекочитаемом виде."""

import re

NON_DIGIT = re.compile(r"[^\d]")


def parse_price(text: str) -> int | None:
    """Достаёт число из строки со стоимостью.

    Цены на сайте приходят как «Стоимость: 16 500 ₽», «от 22 000 ₽» или голым числом
    в скрытом поле формы. Разделителем разрядов служит неразрывный пробел.
    Возвращает None, если чисел в строке нет.
    """
    digits = NON_DIGIT.sub("", text.replace("\xa0", " "))
    return int(digits) if digits else None
